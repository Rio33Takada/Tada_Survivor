        "0:表示する文字----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------▽",
        "1:ああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああああ▽",
