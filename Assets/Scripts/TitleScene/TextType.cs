        "6:--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------▽",
        "7:--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------▽",
        "8:--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------▽",
        "9:--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------▽",
        "10:--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------▽",
        "",
    };

    //タイトルのボタンが押されたら
    public void StartButton()
    {
        StartCoroutine(TypeText(message[currentIndex]));
        currentIndex++;
    }

    //テキスト表示処理
    IEnumerator TypeText(string fullText)
    {
        isTyping = true;
        isTyped = false;

        messageText.text = "";
        foreach (char c in fullText)
        {
            messageText.text += c;
            yield return new WaitForSeconds(TypeSpeed);
        }

        isTyped = true;
        isTyping = false;
    }

