    void Update()
    {
        if ((currentIndex <= 11))
        {
            //早送り
            if (isTyping == true && isTyped == false)
            {
                if (Input.GetMouseButtonDown(0))
                {
                    TypeSpeed = 0f;
                }
            }
            //次の文へ
            else
            {
                if (Input.GetMouseButtonDown(0))
                {
                    TypeSpeed = 0.04f;
                    StartCoroutine(TypeText(message[currentIndex]));
                    currentIndex++;
                }
            }
        }
        else
        {
            SceneManager.LoadScene("MapScene");
        }
    }
}
